/**
 * Admin – QR Detail Page
 * Shows full QR details, image, scan history, and action buttons.
 */
import { api }    from '../components/api.js';
import { setPageTitle } from '../components/layout.js';
import { timeAgo, statusBadge } from '../components/helpers.js';

const resultColor = { valid: '#22c55e', invalid: '#ef4444', expired: '#f59e0b', used: '#6b7280', not_found: '#ef4444' };
const resultLabel = { valid: '✅ Valid', invalid: '❌ Invalid', expired: '⏱️ Expired', used: '🔁 Already Used', not_found: '❓ Not Found' };

export default {
  async render(el, params) {
    setPageTitle('QR Detail');
    el.innerHTML = `<div class="page-spinner"><div class="spinner"></div></div>`;

    try {
      const { qr, history } = await api.qr.detail(params.id);
      setPageTitle(`QR: ${qr.uuid.substring(0, 8)}…`);

      const expDate    = qr.expires_at ? new Date(qr.expires_at) : null;
      const isExpired  = expDate && expDate < new Date();
      const scanPct    = qr.max_scans > 0 ? Math.round((qr.scan_count / qr.max_scans) * 100) : 0;

      el.innerHTML = `
        <div class="page-header">
          <div class="page-header-left">
            <div class="breadcrumb">
              <a href="#/admin/qr">QR Management</a>
              <span class="breadcrumb-sep">/</span>
              <span>Detail</span>
            </div>
            <h2 style="display:flex;align-items:center;gap:10px">
              QR Detail
              ${statusBadge(qr.status)}
            </h2>
          </div>
          <div class="page-header-actions">
            <a href="${api.qr.downloadPng(qr.id)}" class="btn btn-secondary btn-sm" target="_blank">⬇ Download PNG</a>
            <a href="${api.qr.downloadPdf(qr.id)}" class="btn btn-secondary btn-sm" target="_blank">🖨 Print</a>
            ${qr.status === 'active' ? `<button class="btn btn-secondary btn-sm" id="deact-btn">Deactivate</button>` : ''}
            <button class="btn btn-secondary btn-sm" id="regen-btn">🔄 Regenerate</button>
            <button class="btn btn-danger btn-sm" id="del-btn">Delete</button>
          </div>
        </div>

        <div style="display:grid;grid-template-columns:auto 1fr;gap:24px;align-items:start">
          <!-- QR Image card -->
          <div class="card" style="width:280px;text-align:center;padding:24px;flex-shrink:0">
            <img src="${qr.qr_image || ''}" alt="QR Code"
              style="width:220px;height:220px;border-radius:12px;border:3px solid var(--border);object-fit:cover;display:block;margin:0 auto">
            <div style="margin-top:14px">
              <div style="font-family:monospace;font-size:.7rem;color:var(--text-tertiary);word-break:break-all;line-height:1.5">
                ${qr.uuid}
              </div>
              <div style="margin-top:10px;font-size:.75rem;color:${isExpired ? 'var(--danger)' : 'var(--success)'}">
                ${isExpired ? '🔴 Expired' : '🟢 Valid until'}: ${expDate?.toLocaleString('id-ID',{dateStyle:'medium',timeStyle:'short'}) ?? 'No expiry'}
              </div>
            </div>
            <!-- Scan progress bar -->
            <div style="margin-top:16px;text-align:left">
              <div style="display:flex;justify-content:space-between;font-size:.75rem;color:var(--text-tertiary);margin-bottom:4px">
                <span>Scans used</span>
                <span>${qr.scan_count} / ${qr.max_scans}</span>
              </div>
              <div style="background:var(--border);border-radius:99px;height:6px;overflow:hidden">
                <div style="width:${scanPct}%;background:${scanPct >= 100 ? 'var(--danger)' : 'var(--accent)'};height:100%;border-radius:99px;transition:width .4s ease"></div>
              </div>
            </div>
          </div>

          <!-- Details card -->
          <div style="display:flex;flex-direction:column;gap:16px">
            <div class="card">
              <div class="card-header"><span class="card-title">QR Information</span></div>
              <div style="display:grid;grid-template-columns:1fr 1fr;gap:0">
                ${[
                  ['Status',         statusBadge(qr.status)],
                  ['UUID',           `<code style="font-size:.8rem">${qr.uuid}</code>`],
                  ['Site',           qr.site_name || '—'],
                  ['Branch',         qr.branch_name || '—'],
                  ['Ticket Code',    qr.ticket_code || '—'],
                  ['Visit Date',     qr.visit_date ? new Date(qr.visit_date).toLocaleDateString('id-ID') : '—'],
                  ['Ticket Type',    qr.ticket_type_name || '—'],
                  ['Visitor',        qr.visitor_name || '—'],
                  ['Generated By',   `${qr.generated_by_name || '—'} <small style="color:var(--text-tertiary)">(${qr.generated_by_email || ''})</small>`],
                  ['Generated At',   qr.created_at ? new Date(qr.created_at).toLocaleString('id-ID') : '—'],
                  ['Valid From',     qr.valid_from ? new Date(qr.valid_from).toLocaleString('id-ID') : '—'],
                  ['Expires At',     qr.expires_at ? new Date(qr.expires_at).toLocaleString('id-ID') : '—'],
                  ['Max Scans',      qr.max_scans],
                  ['Scan Count',     `<strong>${qr.scan_count}</strong>`],
                  ['Last Scanned',   qr.last_scanned_at ? timeAgo(qr.last_scanned_at) : 'Never'],
                  ['Notes',          qr.notes || '—'],
                ].map(([label, val]) => `
                  <div style="padding:10px 0;border-bottom:1px solid var(--border-subtle)">
                    <div style="font-size:.72rem;color:var(--text-tertiary);text-transform:uppercase;letter-spacing:.05em;margin-bottom:2px">${label}</div>
                    <div style="font-size:.875rem;color:var(--text-primary)">${val}</div>
                  </div>`).join('')}
              </div>
            </div>
          </div>
        </div>

        <!-- Scan History -->
        <div class="card" style="margin-top:16px">
          <div class="card-header">
            <span class="card-title">Scan History</span>
            <span class="badge badge-secondary">${history.length} scans</span>
          </div>
          ${history.length ? `
            <div style="overflow-x:auto">
              <table class="table" style="width:100%">
                <thead><tr><th>Time</th><th>Result</th><th>Scanner</th><th>Visitor</th><th>IP</th><th>Notes</th></tr></thead>
                <tbody>
                  ${history.map(s => `
                    <tr>
                      <td style="white-space:nowrap;font-size:.75rem">${new Date(s.scan_time).toLocaleString('id-ID',{dateStyle:'short',timeStyle:'medium'})}</td>
                      <td>
                        <span style="font-weight:600;color:${resultColor[s.result] || '#888'};font-size:.8125rem">
                          ${resultLabel[s.result] || s.result}
                        </span>
                      </td>
                      <td style="font-size:.8125rem">${s.scanner_name || 'System'}</td>
                      <td style="font-size:.8125rem">${s.visitor_name || '—'}</td>
                      <td style="font-size:.7rem;color:var(--text-tertiary);font-family:monospace">${s.ip_address || '—'}</td>
                      <td style="font-size:.75rem;color:var(--text-tertiary)">${s.notes || '—'}</td>
                    </tr>`).join('')}
                </tbody>
              </table>
            </div>` : `
            <div class="empty-state" style="padding:32px">
              <span class="empty-icon">📭</span>
              <div class="empty-title">No scan history</div>
              <p class="empty-message">This QR code has not been scanned yet.</p>
            </div>`}
        </div>`;

      // Bind action buttons
      el.querySelector('#deact-btn')?.addEventListener('click', async () => {
        if (!confirm('Deactivate this QR code?')) return;
        try {
          await api.qr.update(params.id, { status: 'deactivated' });
          window.toast?.success('QR deactivated');
          await this.render(el, params); // re-render
        } catch (err) { window.toast?.error('Failed', err.message); }
      });

      el.querySelector('#regen-btn')?.addEventListener('click', async () => {
        if (!confirm('Regenerate? The old QR will be deactivated and a new one created.')) return;
        try {
          const res = await api.qr.regenerate(params.id);
          window.toast?.success('QR regenerated – redirecting to new QR');
          window.location.hash = `#/admin/qr/${res.qr.id}`;
        } catch (err) { window.toast?.error('Failed', err.message); }
      });

      el.querySelector('#del-btn')?.addEventListener('click', async () => {
        if (!confirm('Delete this QR code permanently?')) return;
        try {
          await api.qr.delete(params.id);
          window.toast?.success('QR deleted');
          window.location.hash = '#/admin/qr';
        } catch (err) { window.toast?.error('Failed', err.message); }
      });

    } catch (err) {
      el.innerHTML = `
        <div class="empty-state" style="padding:80px 20px">
          <span class="empty-icon">⚠️</span>
          <div class="empty-title">Failed to load QR</div>
          <p class="empty-message">${err.message}</p>
          <a href="#/admin/qr" class="btn btn-secondary">← Back to QR List</a>
        </div>`;
    }
  },
};
